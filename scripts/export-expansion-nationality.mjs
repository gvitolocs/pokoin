#!/usr/bin/env node
/**
 * Derive market/src/data/expansion-nationality.js from suggest-sets.js:
 * { nationality: 'compact compact …' } with the same keys and last-row-wins
 * rule as the set catalog lookup, so print filters and api.js can tell an
 * expansion's print family without shipping the 838 set objects (83 KB) on
 * the first paint. scripts/export-suggest-catalog.py runs this after it
 * rewrites suggest-sets.js; market/src/expansion-nationality.test.js fails
 * when the two drift apart.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import RAW_SETS from '../market/src/data/suggest-sets.js';
import { compactQuery } from '../market/src/compact-query.js';

export function nationalityTable(rows) {
  const byCompact = new Map();
  for (const row of rows || []) {
    byCompact.set(compactQuery(String(row.display || '').trim()), String(row.nationality || '').trim().toLowerCase());
  }
  const groups = {};
  for (const [compact, nationality] of byCompact) {
    if (!compact) continue;
    (groups[nationality] ||= []).push(compact);
  }
  return Object.fromEntries(Object.keys(groups).sort().map((nationality) => [nationality, groups[nationality].sort().join(' ')]));
}

export function nationalityModule(rows) {
  return `// Generated by scripts/export-expansion-nationality.mjs from suggest-sets.js. Do not edit.\nexport default ${JSON.stringify(nationalityTable(rows), null, 1)};\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../market/src/data/expansion-nationality.js');
  fs.writeFileSync(out, nationalityModule(RAW_SETS));
  console.log(`wrote ${out}`);
}
