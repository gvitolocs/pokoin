#!/usr/bin/env bash
# Dump catalog title-language names into market/src/data/localized-names/<lang>.js.
#
# The typeahead name pool is English (D00001H: one English-identity index).
# These per-language tables let a localized query (`evoli`, `glurak`,
# `イーブイ`) resolve to its English catalog name before recall and ranking.
# Each file is a lazy chunk the SPA loads only under that search language.
# Rows: [localized_name, english_name], only where the two differ, only for
# names the suggest pool knows (marketplace_card_names). Re-run after
# scripts/import-catalog-languages.js:
#
#   bash scripts/export-localized-names.sh
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/market/src/data/localized-names"
container="${POKOIN_MARKETPLACE_POSTGRES:-pokoin-marketplace-postgres-15t}"
mkdir -p "$out"

for lang in de es fr it jp ko pt zh zht; do
  body="$(docker exec -i "$container" psql -U pokoin_marketplace -d pokoin_marketplace -X -q -t -A -v ON_ERROR_STOP=1 -v lang="$lang" <<'SQL'
select coalesce(string_agg(json_build_array(l.localized_name, l.name)::text, E',\n' order by l.name, l.localized_name), '')
from public.card_name_languages l
where l.language = :'lang'
  and l.localized_name <> l.name
  and exists (select 1 from public.marketplace_card_names n where n.name = l.name);
SQL
)"
  rows="$(printf '%s' "$body" | grep -c '^\[' || true)"
  if [ "$rows" -lt 500 ]; then
    echo "too few $lang names: $rows" >&2
    exit 1
  fi
  {
    echo "// Generated by scripts/export-localized-names.sh from card_name_languages ($lang). Do not edit."
    echo "export default ["
    printf '%s\n' "$body"
    echo "];"
  } > "$out/$lang.js"
  echo "wrote $rows $lang names to $out/$lang.js"
done
